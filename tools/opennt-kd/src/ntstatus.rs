/// O nome do NTSTATUS (de 32 bits), se conhecido.
pub fn name(status: u32) -> Option<&'static str> {
    NAMES.iter().find(|(value, _)| *value == status).map(|(_, name)| *name)
}

/// O NTSTATUS de um valor de RAX (só os 32 bits de baixo valem).
pub fn of_result(value: u64) -> u32 {
    value as u32
}

/// Erro (severidade 3).
pub fn is_error(status: u32) -> bool {
    status >> 30 == 3
}

/// Aviso (severidade 2).
pub fn is_warning(status: u32) -> bool {
    status >> 30 == 2
}

/// O texto: nome e valor (ou só o valor).
pub fn describe(status: u32) -> String {
    match name(status) {
        Some(name) => format!("{name} ({status:#010x})"),
        None => format!("{status:#010x}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_and_severity() {
        assert_eq!(name(0xC000_0034), Some("STATUS_OBJECT_NAME_NOT_FOUND"));
        assert_eq!(name(0x103), Some("STATUS_PENDING"));
        assert!(is_error(0xC000_0001));
        assert!(!is_error(0x103));
        assert!(is_warning(0x8000_0005));
        assert_eq!(describe(0x1234), "0x00001234");
        assert_eq!(of_result(0xFFFF_FFFF_C000_0022), 0xC000_0022);
    }
}
