//! O barramento raiz do PnP manager (HTREE\ROOT\0).
//!
//! No NT, o PDO da raiz e os dos dispositivos enumerados pela raiz são do
//! `\Driver\PnpManager` (IopPnPDispatch): as BusRelations da raiz são as
//! instâncias de `Enum\Root\<id>\<NNNN>` (com o HardwareID da chave) e os
//! barramentos da plataforma. Aqui os PDOs da raiz não têm DRIVER_OBJECT e
//! o respondedor de PDO do I/O Manager responde por eles: QUERY_ID pelo
//! Registro (DeviceID = `ROOT\<id>`, InstanceID = `NNNN`, HardwareID e
//! CompatibleIDs dos valores da chave), QUERY_CAPABILITIES com UniqueID
//! (o caminho da raiz já é único), BusRelations da raiz e
//! TargetDeviceRelation. O barramento PCI interno (o papel do pci.sys sobre
//! o barramento raiz que a HAL enumera) entra como filho da raiz pelo
//! `add_platform_bus`.

use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;

use super::install;
use crate::ntos::inc::types::{BusQueryIdType, DeviceCapabilities, DeviceObject, DeviceRelationType, DeviceRelations, IoStackLocation, NtStruct};
use crate::ntos::io::io_manager::{self, irp_mj, irp_mn};
use crate::ntos::mm::guest_memory as guest;
use crate::ntos::ob::objects::device as device_objects;
use crate::rtl::{KernelError, SpinLock};

/// Um PDO da raiz: o caminho em `Enum` (vazio para a própria raiz e para
/// os barramentos da plataforma, que respondem por si).
#[derive(Clone)]
struct RootDevice {
    pdo: u64,
    instance_path: String,
}

struct RootBus {
    root_pdo: u64,
    devices: Vec<RootDevice>,
    /// Barramentos da plataforma (PDOs com respondedor próprio).
    platform: Vec<u64>,
}

static ROOT: SpinLock<RootBus> = SpinLock::new(RootBus { root_pdo: 0, devices: Vec::new(), platform: Vec::new() });

const IO_TYPE_DEVICE: i16 = 3;
/// FILE_DEVICE_CONTROLLER e FILE_AUTOGENERATED_DEVICE_NAME, como o
/// IopCreateRootEnumeratedDeviceObject.
const FILE_DEVICE_CONTROLLER: u32 = 4;
const FILE_AUTOGENERATED_DEVICE_NAME: u32 = 0x80;
const DO_BUS_ENUMERATED_DEVICE: u32 = 0x1000;

fn free_pdo(pointer: u64) {
    guest::free_bytes(pointer);
}

/// DEVICE_OBJECT de PDO do PnpManager (sem DRIVER_OBJECT; extensão de 4 bytes).
fn create_pdo() -> Result<u64, KernelError> {
    let pdo = guest::alloc_bytes(DeviceObject::SIZE + 8);
    // SAFETY: bloco zerado recém-alocado do tamanho de um DEVICE_OBJECT.
    let device = unsafe { DeviceObject::at(pdo) };
    device.type_.set(IO_TYPE_DEVICE);
    device.size.set(DeviceObject::SIZE as u16);
    device.reference_count.set(1);
    device.device_type.set(FILE_DEVICE_CONTROLLER);
    device.characteristics.set(FILE_AUTOGENERATED_DEVICE_NAME);
    device.flags.set(DO_BUS_ENUMERATED_DEVICE);
    device.stack_size.set(1);
    device.device_extension.set(pdo + DeviceObject::SIZE);
    device_objects::register(pdo, Some(free_pdo), None)?;
    super::publish_autogenerated_pdo(pdo)?;
    Ok(pdo)
}

/// Cria (uma vez) o PDO da raiz e os dos dispositivos de `Enum\Root`.
pub fn initialize() -> Result<u64, KernelError> {
    if ROOT.lock().root_pdo != 0 {
        return Ok(ROOT.lock().root_pdo);
    }
    let root_pdo = create_pdo()?;
    let mut devices = Vec::new();
    let root_key = format!("{}\\Enum\\Root", install::CONTROL_SET);
    for id in crate::ntos::cm::registry::list_keys(&root_key) {
        for instance in crate::ntos::cm::registry::list_keys(&format!("{root_key}\\{id}")) {
            let path = format!("ROOT\\{}\\{instance}", id.to_uppercase());
            if install::read_multi(&format!("{root_key}\\{id}\\{instance}"), "HardwareID").is_empty() {
                continue;
            }
            devices.push(RootDevice { pdo: create_pdo()?, instance_path: path });
        }
    }
    {
        let mut root = ROOT.lock();
        root.root_pdo = root_pdo;
        root.devices = devices;
    }
    io_manager::register_pdo_native_answerer(answer_root_irp);
    Ok(root_pdo)
}

/// Barramento da plataforma, filho da raiz (o PCI interno).
pub fn add_platform_bus(pdo: u64) {
    let mut root = ROOT.lock();
    if !root.platform.contains(&pdo) {
        root.platform.push(pdo);
    }
}

/// String UTF-16 em pool (uma ou várias, com o NUL duplo).
fn pool_strings(items: &[String]) -> u64 {
    let mut bytes = Vec::new();
    for item in items {
        bytes.extend(item.encode_utf16().flat_map(|unit| unit.to_le_bytes()));
        bytes.extend_from_slice(&[0, 0]);
    }
    bytes.extend_from_slice(&[0, 0]);
    let buffer = guest::alloc_bytes(bytes.len() as u64);
    guest::write_bytes(buffer, &bytes);
    buffer
}

/// DEVICE_RELATIONS em pool com os PDOs referenciados.
fn relations(devices: &[u64]) -> u64 {
    let size = DeviceRelations::SIZE + devices.len().saturating_sub(1) as u64 * 8;
    let address = guest::alloc_bytes(size);
    // SAFETY: DEVICE_RELATIONS recém-alocada com `devices.len()` entradas.
    let list = unsafe { DeviceRelations::at(address) };
    list.count.set(devices.len() as u32);
    // SAFETY: Objects[] segue o cabeçalho na mesma alocação.
    let objects = unsafe { crate::ntos::inc::field::Field::<u64>::array_at(list.objects[0].address(), devices.len()) };
    for (slot, &device) in objects.iter().zip(devices) {
        let _ = device_objects::reference(device);
        slot.set(device);
    }
    address
}

/// IopPnPDispatch para a raiz e os dispositivos enumerados por ela.
fn answer_root_irp(device: u64, packet: u64) -> Option<i32> {
    let (root_pdo, entry, children) = {
        let root = ROOT.lock();
        let entry = root.devices.iter().find(|candidate| candidate.pdo == device).cloned();
        if device != root.root_pdo && entry.is_none() {
            return None;
        }
        let children: Vec<u64> = root.platform.iter().copied().chain(root.devices.iter().map(|candidate| candidate.pdo)).collect();
        (root.root_pdo, entry, children)
    };
    let (irp, location) = crate::drivers::bus::motherboard::current_stack_location(packet);
    let major = location.major_function.get();
    let mut status = irp.io_status.status.get();
    let mut information = irp.io_status.information.get();
    if major == irp_mj::POWER {
        status = 0;
    } else if major == irp_mj::PNP {
        if let Some((new_status, new_information)) = answer_pnp(device, root_pdo, entry.as_ref(), &children, location) {
            status = new_status;
            information = new_information;
        }
    }
    irp.io_status.status.set(status);
    irp.io_status.information.set(information);
    io_manager::iof_complete_request(packet);
    Some(status)
}

fn answer_pnp(device: u64, root_pdo: u64, entry: Option<&RootDevice>, children: &[u64], location: &IoStackLocation) -> Option<(i32, u64)> {
    match location.minor_function.get() {
        // START, QUERY_REMOVE, REMOVE, CANCEL_REMOVE, STOP, QUERY_STOP,
        // CANCEL_STOP e SURPRISE_REMOVAL: aceitos.
        0..=6 | irp_mn::SURPRISE_REMOVAL => Some((0, 0)),
        irp_mn::QUERY_DEVICE_RELATIONS => {
            let relation = location.parameters.query_device_relations.type_.get();
            if relation == DeviceRelationType::BUS_RELATIONS && device == root_pdo {
                return Some((0, relations(children)));
            }
            (relation == DeviceRelationType::TARGET_DEVICE_RELATION).then(|| (0, relations(&[device])))
        }
        irp_mn::QUERY_CAPABILITIES => {
            // SAFETY: DEVICE_CAPABILITIES do IRP.
            let capabilities = unsafe { DeviceCapabilities::at(location.parameters.device_capabilities.capabilities.get()) };
            capabilities.set_unique_id(1);
            capabilities.set_silent_install(1);
            Some((0, 0))
        }
        irp_mn::QUERY_ID => {
            let id_type = location.parameters.query_id.id_type.get();
            if device == root_pdo {
                let text = match id_type {
                    BusQueryIdType::BUS_QUERY_DEVICE_ID => "HTREE\\ROOT",
                    BusQueryIdType::BUS_QUERY_INSTANCE_ID => "0",
                    _ => return None,
                };
                return Some((0, pool_strings(&[String::from(text)])));
            }
            let entry = entry?;
            let key = format!("{}\\Enum\\{}", install::CONTROL_SET, entry.instance_path);
            let (device_id, instance) = entry.instance_path.rsplit_once('\\')?;
            let strings = match id_type {
                BusQueryIdType::BUS_QUERY_DEVICE_ID => alloc::vec![String::from(device_id)],
                BusQueryIdType::BUS_QUERY_INSTANCE_ID => alloc::vec![String::from(instance)],
                BusQueryIdType::BUS_QUERY_HARDWARE_I_DS => install::read_multi(&key, "HardwareID"),
                BusQueryIdType::BUS_QUERY_COMPATIBLE_I_DS => install::read_multi(&key, "CompatibleIDs"),
                _ => return None,
            };
            if strings.is_empty() {
                return None;
            }
            Some((0, pool_strings(&strings)))
        }
        _ => None,
    }
}

/// PDO da raiz (0 antes do `initialize`).
pub fn root_pdo() -> u64 {
    ROOT.lock().root_pdo
}
